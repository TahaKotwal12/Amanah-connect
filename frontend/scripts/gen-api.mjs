// Generate src/types/api.generated.ts from the running backend's OpenAPI document.
//   npm run gen:api                          -> http://localhost:8080/v3/api-docs
//   OPENAPI_URL=https://host/v3/api-docs npm run gen:api
// (springdoc is enabled in the backend's `local` profile only.) Works on Windows, macOS and Linux:
// no shell syntax, so it does not depend on the shell npm happens to use.
import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const url = process.env.OPENAPI_URL ?? 'http://localhost:8080/v3/api-docs'
const out = new URL('../src/types/api.generated.ts', import.meta.url)

const response = await fetch(url)
if (!response.ok) {
  console.error(
    `Could not read ${url}: HTTP ${response.status}. Is the backend running with the local profile?`,
  )
  process.exit(1)
}

const ast = await openapiTS(await response.json())
const header = `// Generated by scripts/gen-api.mjs from the backend's /v3/api-docs. Do not edit: run \`npm run gen:api\`.\n/* eslint-disable */\n`
await writeFile(out, header + astToString(ast))
console.log(`Wrote ${out.pathname.replace(/^\/([A-Za-z]:)/, '$1')}`)
